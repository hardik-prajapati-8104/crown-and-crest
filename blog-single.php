            <p style="font-size: 1.1rem; color: var(--ink)">
              A corporate event is a business tool: it should move a metric,
              strengthen a relationship or launch a message. This checklist
              keeps the planning focused on outcomes.
            </p>
            <h2>1. Define the objective</h2>
            <p>
              Write one sentence describing what success looks like: leads
              generated, partners thanked, a product understood. Every later
              decision should serve it.
            </p>
            <h2>2. Set the budget and contingency</h2>
            <p>
              Agree the total budget early and hold back 10–15% for the
              unexpected. Itemise venue, production, catering, talent, marketing
              and staffing.
            </p>
            <h2>3. Choose the date and venue</h2>
            <p>
              Check public holidays, religious observances, competing industry
              events and peak-season availability. Visit the venue at the same
              time of day as the event.
            </p>
            <h2>4. Build the guest experience</h2>
            <p>
              Map the journey from invitation to departure: registration,
              welcome, flow, seating, content and farewell. Remove friction at
              every step.
            </p>
            <h2>5. Brief suppliers early</h2>
            <p>
              Catering, AV, décor, talent and transport should all work from one
              run-sheet. Early briefing reduces cost and mistakes.
            </p>
            <h2>6. Plan for permits and compliance</h2>
            <p>
              Entertainment, music, lighting effects and outdoor set-ups may
              require approvals. Confirm requirements with your venue, planner
              and the relevant authorities well in advance.
            </p>
            <h2>7. Rehearse the programme</h2>
            <p>
              Run speeches, cues, audio-visual content and transitions at least
              once. Rehearsal is the cheapest insurance an event can buy.
            </p>
            <h2>8. Prepare a contingency plan</h2>
            <p>
              Weather, late speakers, technical failures and guest surges are
              predictable. Decide the response before the day.
            </p>
            <h2>9. Manage the day on site</h2>
            <p>
              Appoint one decision-maker, brief the team before doors open and
              keep a clear communication channel for every supplier.
            </p>
            <h2>10. Measure and debrief</h2>
            <p>
              Collect feedback, compare against the original objective and
              record what to repeat or improve next time.
            </p>
            <blockquote>
              Events are won in preparation. By the time guests arrive, the
              experience should already be decided.
            </blockquote>
